-- Патч: таблица для rate limiting чувствительных форм (логин, регистрация,
-- восстановление пароля, отклик на кампанию).
--
-- Контекст: сайт крутится на Vercel как serverless-функции — у Server Actions
-- нет общей памяти между вызовами (запрос может попасть на любой из множества
-- независимых инстансов), поэтому классический "счётчик в памяти процесса" тут
-- не работает вообще: злоумышленник просто подождёт, пока его запросы попадут
-- на "свежий" инстанс с обнулённым счётчиком. Единственное место, до которого
-- дотягивается любой инстанс — сама база, которая у площадки и так одна.
--
-- Как это работает (см. src/lib/rate-limit.ts): перед каждой чувствительной
-- операцией код считает, сколько строк в этой таблице накопилось для данного
-- ключа (например "login:1.2.3.4" или "apply:<user_id>") за последние N секунд.
-- Если лимит уже достигнут — операция блокируется с понятной ошибкой
-- (errors.tooManyAttempts) до того, как дойти до Supabase Auth / вставки в БД;
-- если нет — пишется новая строка-отметка и операция выполняется как обычно.
-- Старые отметки подчищаются сами по себе (см. rate-limit.ts), отдельный
-- крон под это заводить не стали.
--
-- RLS включён БЕЗ единой policy — таблица недоступна анонимному и обычному
-- authenticated-запросу вообще, читать и писать в неё может только
-- service_role-соединение (он и так обходит RLS по определению) — то же самое
-- соединение, что уже используется для одобрения эдиторов
-- (createServiceRoleClient в src/lib/supabase/server.ts).
--
-- Как выполнить: Supabase -> SQL Editor -> New query -> вставить весь файл -> Run.
-- Безопасно выполнять повторно.

create table if not exists public.rate_limit_events (
  id bigserial primary key,
  key text not null,
  created_at timestamptz not null default now()
);

create index if not exists rate_limit_events_key_created_idx
  on public.rate_limit_events (key, created_at desc);

alter table public.rate_limit_events enable row level security;
-- Ни одной policy не добавляем — значит доступ есть только у service_role.
-- anon и authenticated-ключи не смогут ни прочитать, ни записать сюда ни
-- строки напрямую через Supabase API, даже если узнают имя таблицы.

