import { cookies } from 'next/headers';

export type Locale = 'ru' | 'en';

const LOCALE_COOKIE = 'locale';

export async function getLocale(): Promise<Locale> {
  const store = await cookies();
  return store.get(LOCALE_COOKIE)?.value === 'en' ? 'en' : 'ru';
}

